  /* Reuse / Re-measure / Replace logic shared by the spec page, lab and quiz. */
  function judge(spec, value) {
    if (spec.dir === "none") return { verdict: "check", why: "There is no reject size in our table for this, so check the manual." };
    if (spec.dir === "oor") {
      const band = 0.0005;
      if (value >= spec.rejVal) return { verdict: "replace", why: `Out-of-round ${fmt(value, 4)} in is at or past the 0.0015 in reject limit. The cylinder needs to be resized (bored oversize) or the block replaced.` };
      if (value >= spec.rejVal - band) return { verdict: "remeasure", why: `Out-of-round ${fmt(value, 4)} in is very close to the 0.0015 in reject limit. Clean the bore, let it cool, and measure again before deciding.` };
      return { verdict: "reuse", why: `Out-of-round ${fmt(value, 4)} in is well under the 0.0015 in reject limit.` };
    }
    const range = Math.abs(spec.rejVal - spec.stdVal);
    const band = Math.max(0.0005, range * 0.25);
    const past = spec.dir === "min" ? value <= spec.rejVal + 1e-9 : value >= spec.rejVal - 1e-9;
    const dist = Math.abs(value - spec.rejVal);
    const word = spec.dir === "min" ? "worn smaller" : "worn bigger";
    if (past) return { verdict: "replace", why: `${fmt(value)} in is at or past the reject size of ${spec.reject}. The part is ${word} than allowed.` };
    if (dist < band - 1e-9) return { verdict: "remeasure", why: `${fmt(value)} in is within ${fmt(band, 4)} in of the reject size (${spec.reject}). That is too close to call: clean it, let it cool, re-zero the tool, and measure again.` };
    return { verdict: "reuse", why: `${fmt(value)} in is inside the limits (standard ${spec.std}, reject ${spec.reject}).` };
  }
  function fmt(v, d) {
    d = d || 3;
    return Number(v).toFixed(d);
  }

